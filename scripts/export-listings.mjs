#!/usr/bin/env node
/**
 * Export runtime listings to properties.ts with generated slugs.
 * Run after editing listings in admin dashboard.
 * 
 * Usage: node scripts/export-listings.mjs
 */

import fs from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.join(__dirname, "..");

function slugify(text) {
  return text
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .slice(0, 60);
}

async function main() {
  try {
    // Read listings from store
    const listingsPath = path.join(PROJECT_ROOT, ".hermes", "store", "listings.json");
    const listingsData = await fs.readFile(listingsPath, "utf-8");
    const listings = JSON.parse(listingsData);

    if (!Array.isArray(listings) || listings.length === 0) {
      console.log("No listings found in store.");
      return;
    }

    // Generate slugs and validate
    const enriched = listings.map((listing) => {
      if (!listing.slug) {
        listing.slug = slugify(listing.title);
      }
      return listing;
    });

    // Check for duplicate slugs
    const slugs = enriched.map((l) => l.slug);
    const uniqueSlugs = new Set(slugs);
    if (uniqueSlugs.size !== slugs.length) {
      console.error("ERROR: Duplicate slugs detected!");
      slugs.forEach((slug, i) => {
        if (slugs.indexOf(slug) !== i) {
          console.error(`  - "${slug}" (listings ${slugs.indexOf(slug)} and ${i})`);
        }
      });
      process.exit(1);
    }

    // Generate TypeScript file
    const propertiesContent = `import type { Property } from "@/lib/types";
import { isPublicListing } from "@/lib/listing-access";

/**
 * Runtime listings exported from store/listings.json
 * Generated by scripts/export-listings.mjs
 * 
 * All listings are stored in this file and used throughout the catalog, search, and property pages.
 * To update: edit listings in admin dashboard, then run: node scripts/export-listings.mjs
 */

export const properties: Property[] = ${JSON.stringify(enriched, null, 2)};

export function getPropertyBySlug(slug: string) {
  return properties.find((p) => p.slug === slug);
}

export function getPropertyById(id: string) {
  return properties.find((p) => p.id === id);
}

export function getPropertiesByAgency(agencyId: string) {
  return properties.filter((p) => p.agencyId === agencyId && isPublicListing(p));
}

export function getPropertiesByAgent(agentId: string) {
  return properties.filter((p) => p.agentId === agentId && isPublicListing(p));
}

export function getPropertiesByProject(projectId: string) {
  return properties.filter((p) => p.projectId === projectId && isPublicListing(p));
}

export function getRelatedProperties(property: Property, limit = 3, source: Property[] = properties) {
  return source
    .filter(
      (p) =>
        p.id !== property.id &&
        isPublicListing(p) &&
        (p.location.citySlug === property.location.citySlug ||
          p.propertyType === property.propertyType),
    )
    .slice(0, limit);
}
`;

    const propertiesPath = path.join(PROJECT_ROOT, "src", "data", "properties.ts");
    await fs.writeFile(propertiesPath, propertiesContent);

    console.log(`✅ Exported ${enriched.length} listings to src/data/properties.ts`);
    enriched.forEach((listing) => {
      console.log(`  - ${listing.title.slice(0, 50)}... [${listing.slug}]`);
    });
  } catch (error) {
    console.error("ERROR:", error.message);
    process.exit(1);
  }
}

main();
